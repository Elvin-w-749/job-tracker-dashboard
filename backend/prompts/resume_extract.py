RESUME_EXTRACT_PROMPT = """你是一个专业的 HR 助手，请从以下简历内容中提取求职者的背景摘要，用于后续 JD 匹配度分析。

请用一段简洁的中文总结求职者的核心背景，包含以下要素（如有则提取，无法识别则跳过）：
- 工作年限、核心岗位方向（如「AI 产品经理」、「前端开发工程师」）
- 核心技能栈（列出关键技能，用逗号分隔）
- 行业领域经验
- 学历背景（如大学、专业、学位）
- 过往知名公司/项目经验

输出格式：直接返回一段流畅的中文描述，约 50-120 字，不要输出 JSON，不要包含任何前缀或标记。

示例输出：
「有 5 年经验的 AI 产品经理，毕业于北京大学计算机专业，曾在字节跳动负责大模型应用产品设计，擅长数据分析、用户研究、项目管理」

---

简历内容：
{resume_text}
"""


def build_resume_extract_prompt(resume_text: str) -> str:
    """根据简历文本构建简历解析 prompt"""
    return RESUME_EXTRACT_PROMPT.format(resume_text=resume_text[:8000])